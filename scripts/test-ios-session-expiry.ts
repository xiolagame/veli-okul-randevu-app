import assert from 'node:assert/strict';
import { createToken, verifyToken } from '../server/auth';
import { AuthSessionManager } from '../src/platform/auth-session';
import { applyUnauthorizedSessionPolicy } from '../src/platform/api-session-policy';
const subject={userId:'synthetic-ios-user',phone:'+905550000000',auth_version:1,auth_method:'phone_centric' as const};
const before=Math.floor(Date.now()/1000);
const token=createToken(subject);
const payload=JSON.parse(Buffer.from(token.split('.')[1],'base64url').toString());
assert(payload.exp-before>=86400 && payload.exp-before<=86401);
assert.equal(verifyToken(token)?.auth_method,'phone_centric');
const expired=createToken(subject,-1);
assert.equal(verifyToken(expired),null);
assert.equal(verifyToken(token.slice(0,-1)+'!'),null);
let stored:string|null=expired;
const session=new AuthSessionManager({get:async()=>stored,set:async value=>{stored=value;},remove:async()=>{stored=null;}});
let invalidated=0;session.subscribe(()=>invalidated++);
await session.hydrate();
assert.equal(await applyUnauthorizedSessionPolicy(401,'/api/user/me',expired,session),true);
assert.equal(await session.getToken(),null);assert.equal(stored,null);assert.equal(invalidated,1);
console.log('24-hour server token expiry, signature rejection and expired-session 401 cleanup PASS. No refresh endpoint added.');
